//! 各系统的物理键码 → W3C `KeyboardEvent.code` 名称。
//!
//! 统计只按物理位置记录，与键盘布局、输入法无关；前端用同一套名称把次数画到键盘上。
//! 映射表是纯函数，所有平台都编译并测试。

/// 无法识别的按键统一记为这个名称
pub const UNIDENTIFIED: &str = "Unidentified";

/// 修饰键位：用于组合键统计
pub const CTRL: u8 = 1;
pub const ALT: u8 = 2;
pub const SHIFT: u8 = 4;
pub const META: u8 = 8;

/// 修饰键本身对应的位；不是修饰键返回 0（Caps Lock、Fn 不参与组合键）
pub fn modifier_bit(code: &str) -> u8 {
    match code {
        "ControlLeft" | "ControlRight" => CTRL,
        "AltLeft" | "AltRight" => ALT,
        "ShiftLeft" | "ShiftRight" => SHIFT,
        "MetaLeft" | "MetaRight" => META,
        _ => 0,
    }
}

/// 组合键名称，如 `Ctrl+Shift+KeyS`；只有按住 Ctrl / Alt / Meta 时才算组合键，
/// 单独的 Shift 只是输入大写或符号；修饰键本身不构成组合键
pub fn combo(mods: u8, code: &str) -> Option<String> {
    if mods & (CTRL | ALT | META) == 0 || modifier_bit(code) != 0 || code == "Fn" {
        return None;
    }
    let mut out = String::new();
    for (bit, name) in [
        (CTRL, "Ctrl"),
        (ALT, "Alt"),
        (SHIFT, "Shift"),
        (META, "Meta"),
    ] {
        if mods & bit != 0 {
            out.push_str(name);
            out.push('+');
        }
    }
    out.push_str(code);
    Some(out)
}

